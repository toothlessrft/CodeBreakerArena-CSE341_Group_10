    CALL CLEAR_SCREEN
    CALL SHOW_TITLE

    PRINTS DASH_LINE

    PRINTS MSG_P1
    MOV AL, ATTEMPTS1
    PUTDIG
    PRINTS MSG_OF
    MOV AL, MAXTRIES
    PUTDIG
    PRINTS MSG_SCORE_SHORT
