SHOW_DASHBOARD ENDP


DISPLAY_RESULT PROC
    PRINTS RESULT_TOP

    PRINTS MSG_EXACT
    MOV AL, CORRECTPOS
    PUTDIG

    PRINTS MSG_MISPLACED
    MOV AL, WRONGPOS
    PUTDIG

    PRINTS MSG_ATTEMPT

    CMP CURRENTPLAYER, 1
    JE DR_P1

    MOV AL, ATTEMPTS2
    PUTDIG
    JMP DR_ATTEMPT_DONE

DR_P1:
    MOV AL, ATTEMPTS1
    PUTDIG

DR_ATTEMPT_DONE:
    PRINTS MSG_OF
    MOV AL, MAXTRIES
    PUTDIG

    PRINTS MSG_SCORE

    CMP CURRENTPLAYER, 1
    JE DR_SCORE_P1

    MOV AX, SCORE2
    CALL PRINT_NUM
    JMP DR_DONE

DR_SCORE_P1:
    MOV AX, SCORE1
    CALL PRINT_NUM

DR_DONE:
    PRINTS DASH_LINE
    RET
DISPLAY_RESULT ENDP


SHOW_SECRET_VALUE PROC
    MOV SI, 0

SV_LOOP:
    MOV AL, SECRET[SI]
    PUTDIG

    INC SI
    CMP SI, CODELEN
    JL SV_LOOP

    RET
SHOW_SECRET_VALUE ENDP


PRINT_NUM PROC
    MOV BX, 10
    MOV CX, 0

PN_DIVIDE:
    MOV DX, 0
    DIV BX

    PUSH DX
    INC CX

    CMP AX, 0
    JNZ PN_DIVIDE

PN_PRINT:
    POP DX
    ADD DL, 30H

    MOV AH, 2
    INT 21H

    LOOP PN_PRINT
    RET
PRINT_NUM ENDP


CLEAR_SCREEN PROC
    MOV AX, 0003H
    INT 10H
    RET
CLEAR_SCREEN ENDP


WAIT_KEY PROC
    MOV AH, 08H
    INT 21H
    RET
WAIT_KEY ENDP

