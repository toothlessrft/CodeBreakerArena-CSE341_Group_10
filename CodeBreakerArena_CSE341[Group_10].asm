    CALL PRINT_NUM

    PRINTS MSG_P2
    MOV AL, ATTEMPTS2
    PUTDIG
    PRINTS MSG_OF
    MOV AL, MAXTRIES
    PUTDIG
    PRINTS MSG_SCORE_SHORT
